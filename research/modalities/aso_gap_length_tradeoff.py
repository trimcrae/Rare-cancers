GAP_LENGTH_LIT = os.path.join(REPO, "research", "manuscripts", "aso",
                              "lit-targets-aso-gap-length.json")

#: The geometries compared. The empty suffix is the committed 5-6-5 panel every published number in
#: this lane is derived from; it is the BASELINE and is never regenerated by this module.
#: ⚠ `wing` is 5 throughout on purpose. Varying the wing and the gap at once would confound the two,
#: and the wing is the half the manuscript's thermodynamics already treats as fixed (each parent
#: pairs exactly one five-nucleotide LNA wing). This asks one question: what does the GAP do?
GEOMETRIES = (
    {"suffix": "", "oligo_len": 16, "wing": 5, "role": "baseline — the panel the manuscript reports"},
    {"suffix": "-18mer-5-8-5", "oligo_len": 18, "wing": 5, "role": "longer gap, inside the reported optimum"},
    {"suffix": "-20mer-5-10-5", "oligo_len": 20, "wing": 5, "role": "longer gap, top of the reported optimum"},
)

#: ⛔ REPORTED MINIMA, NOT THRESHOLDS THIS REPOSITORY MEASURED, AND BOTH ENDS ARE CARRIED. The
#: retrieved sources disagree by one nucleotide — five and six — and picking either alone would
#: decide the headline: at five, every 5-10-5 design's parent-side DNA run qualifies; at six, fewer
#: do. So the count is emitted at BOTH and neither is presented as the answer. The verbatim sentences
#: are read from the committed anchor at run time rather than restated here, so this module cannot
#: drift from the evidence it cites (gate 4 discipline: a remembered quotation is the failure mode).
MIN_CONTIGUOUS_DNA_NT = (5, 6)

#: Which anchored quote supports each end. Keyed by (pmid, fragment) so a change to either side of
#: the anchor file fails the build instead of silently re-basing the claim.
_DNA_MIN_ANCHORS = {
    5: ("39126066", "requires a gap size of at least five for cleavage to occur"),
    6: ("41614678", "sufficient to activate RNase H. In general, this is six or more bases"),
}


def _anchor_quotes():
    """The verbatim sentences behind `MIN_CONTIGUOUS_DNA_NT`, read from the committed anchor file.

    RAISES if a fragment is missing. An absent quotation is not a quotation of absence: a threshold
    whose evidence cannot be found must stop this module, not be emitted with the citation dropped.
    """
    with open(GAP_LENGTH_LIT, encoding="utf-8") as fh:
        lit = json.load(fh)
    by_pmid = {r["pmid"]: r for r in lit["records"]}
    out = {}
    for nt, (pmid, fragment) in sorted(_DNA_MIN_ANCHORS.items()):
        rec = by_pmid.get(pmid)
        if rec is None:
            raise RuntimeError(f"lit-targets-aso-gap-length.json holds no PMID {pmid}")
        q = next((q for q in rec["quotes"] if q["fragment"] == fragment), None)
        if q is None:
            raise RuntimeError(f"PMID {pmid} carries no quote fragment {fragment!r} — the threshold "
                               f"of {nt} nt has lost its anchor")
        out[str(nt)] = {"pmid": pmid, "fragment": fragment, "title": rec.get("title"),
                        "full_text_path": rec.get("full_text_path")}
    return out, lit.get("source")


def _read(name):
    p = os.path.join(HERE, name)
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


