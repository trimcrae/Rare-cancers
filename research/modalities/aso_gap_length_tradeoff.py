"""What a LONGER catalytic gap costs and buys at the same NR4A3 fusion-junction seams.

⛔ WHY THIS EXISTS. The screened design space was one geometry: the 16-mer 5-6-5 LNA/DNA/LNA
gapmer. The submission manuscript's own Methods say why that is the weak point rather than a
detail — reported minima for the contiguous DNA run are five to six nucleotides, and for LNA/DNA/LNA
gapmers specifically a six-nucleotide gap gives "noteworthy but incomplete" activity with seven to
ten reported as optimal — and its Limitations concede that "nothing here bounds what a longer
catalytic gap would achieve at the same seams". A six-nucleotide gap was retained because it is the
gap at which a 16-mer admits junction-spanning registers at all. So the most likely reason this
modality fails at a bench is the gap length, and the unexplored design space attacks that directly.

⛔⛔ THE TWO QUANTITIES MOVE IN OPPOSITE DIRECTIONS AND THIS FILE REFUSES TO COMBINE THEM. Lengthening
the gap raises the gap-level margin — junction-unique DNA on the shorter side, the discriminator the
paper ranks by — and it lengthens the whole oligonucleotide, which is more sequence available to
match something else and a smaller share of the duplex that the seam makes unique. A single score
over the two would hide exactly the finding worth reporting, so every readout below is emitted as a
pair and the artifact carries no composite rank.

⭐ AND THE SHARPEST FORM OF THE COST IS ARITHMETIC, NOT A SEARCH RESULT. Inside the catalytic gap,
the junction-unique bases on the shorter side and the bases a WILD-TYPE PARENT pairs on the longer
side are complements: they sum to the gap. ⛔ WITHIN A GEOMETRY THAT MAKES THEM MOVE INVERSELY —
raising the margin LOWERS, by the same nucleotide, the contiguous DNA one wild-type parent pairs at
the design's own seam. What costs is a LONGER GAP, which is the only way to raise the margin past a
geometry's ceiling of half its gap rounded down, and which raises the parent-paired run at every
register — the quantity RNase-H1's own minimum is stated in. That is not a coincidence a better search could
dodge and no screen in this repository was measuring it, because it is a property of the geometry
rather than of the transcriptome.

WHAT THIS IS AND IS NOT
  · It is sequence and duplex arithmetic over committed artifacts, plus whatever transcriptome
    screens are present for each geometry. $0, offline, no network and no credentials.
  · It is NOT a potency, knockdown, delivery, tolerability, safety, therapeutic-window or
    clinical-readiness claim, and computes no such quantity.
  · It is NOT a cleavage measurement. No RNase-H1 assay exists anywhere in this repository. The
    thresholds below are REPORTED MINIMA from the literature this repository has retrieved, applied
    to predicted duplexes; a duplex is necessary for cleavage and is not sufficient.
  · It is NOT a recommendation of a longer gap. It measures a trade and reports both ends.

Output: aso-gap-length-tradeoff.json
"""
