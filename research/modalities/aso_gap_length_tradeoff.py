def design_rows(geom):
    """Every fusion-specific design at this geometry, with both halves of the gap accounted for."""
    atlas = _read(f"nr4a3-fusion-junction-atlas{geom['suffix']}.json")
    if atlas is None:
        return None, None
    gap = geom["oligo_len"] - 2 * geom["wing"]
    pgp = _read(f"aso-parent-gap-pairing{geom['suffix']}.json") or {}
    duplex = {(r["junction"], r["antisense_5to3"]): r for r in pgp.get("per_design", [])}
    thermo = _read(f"junction-aso-thermo{geom['suffix']}.json") or {}
    dg = {(r["junction"], r["antisense_5to3"]): r for r in thermo.get("per_design", [])}
    pre = _read(f"aso-premrna-offtarget{geom['suffix']}.json") or {}
    premrna = {(r.get("junction_label"), r.get("antisense_5to3")): r
               for r in (pre.get("per_design") or [])}

    rows = []
    for panel in atlas["panels"]:
        label = panel["junction_label"]
        for d in panel.get("designs") or []:
            if not d.get("fusion_specific"):
                continue
            k = (label, d["antisense_5to3"])
            gl, gr = d["gap_bases_from_EWSR1"], d["gap_bases_from_NR4A3"]
            if gl + gr != gap:                    # the complement identity IS the finding; check it
                raise RuntimeError(f"{k}: gap halves {gl}+{gr} do not sum to the gap {gap}")
            margin = min(gl, gr)
            parent_dna = max(gl, gr)              # = gap - margin, by the identity just asserted
            t, p = dg.get(k), premrna.get(k)
            rows.append({
                "junction": label,
                "donor": panel["donor_symbol"],
                "antisense_5to3": d["antisense_5to3"],
                "gc_percent": d["gc_percent"],
                "bases_from_donor": d["bases_from_EWSR1"],
                "bases_from_acceptor": d["bases_from_NR4A3"],
                # ── the direction that IMPROVES with a longer gap ──────────────────────────────
                "gap_specificity_margin": margin,
                # ── the direction that WORSENS, and it is the same subtraction ─────────────────
                #: contiguous DNA of the catalytic gap that ONE wild-type parent pairs at this
                #: design's own seam. Guaranteed by construction, not a search result.
                "parent_paired_gap_dna_nt": parent_dna,
                #: that run plus the LNA wing on the same side — the whole contiguous hybrid this
                #: design presents to that wild-type parent.
                "parent_seam_hybrid_bp": parent_dna + geom["wing"],
                "which_parent_pairs_the_longer_side": (
                    panel["donor_symbol"] if gl > gr else "NR4A3" if gr > gl else "both equally"),
                #: The share of the WHOLE duplex the seam makes unique: the oligonucleotide pairs
                #: the fusion over all of it and the best-matching parent over max(donor, acceptor)
                #: of it, so what is left is min(donor, acceptor). ⚠ A CENTRED DESIGN HOLDS THIS AT
                #: 0.5 AT EVERY LENGTH — centring is scale-free — so the erosion a longer oligo
                #: causes is not visible in the best register and shows only in the worst, where the
                #: minimum side is pinned at WING+1 whatever the length. That is why this is
                #: reported as a distribution and never as a per-geometry mean.
                "junction_unique_fraction_of_oligo": round(
                    min(d["bases_from_EWSR1"], d["bases_from_NR4A3"]) / geom["oligo_len"], 4),
                # ── coincidence screens, which a longer gap makes HARDER to trip ───────────────
                "mature_parent_duplex_through_whole_gap_bp":
                    (duplex.get(k) or {}).get("longest_parent_duplex_bp_through_gap"),
                "mature_parent_duplex_gene": (duplex.get(k) or {}).get("parent"),
                # ⚠ THE FIELD IS `n_hybridisable_gap_fully_paired`. A near-miss key name returns
                # None through `.get`, and None reads as "not screened" — so a mis-typed key would
                # have reported the whole pre-mRNA arm as absent at every geometry while the arm had
                # in fact run and answered. Caught by the summary printing None for all three.
                "premrna_hybridisable_gap_paired_sites":
                    (p or {}).get("n_hybridisable_gap_fully_paired") if p else None,
                "premrna_hits_invisible_to_mature_screens":
                    (p or {}).get("n_invisible_to_mature_screens") if p else None,
                # ── duplex thermodynamics ─────────────────────────────────────────────────────
                "dg37_fusion_duplex": (t or {}).get("dg37_fusion_duplex"),
                "dg37_most_stable_parent_duplex": (t or {}).get("dg37_best_parent_duplex"),
                "ddg37_discrimination": (t or {}).get("ddg37_discrimination"),
                "design_rules_passed": (sum((t or {}).get("design_rules", {}).values())
                                        if t else None),
                "also_exact_at_junctions": d.get("also_exact_in_junctions") or [],
            })
    return atlas, rows


#: The seam the one clinically-relevant candidate sits on: the most commonly reported EMC junction
