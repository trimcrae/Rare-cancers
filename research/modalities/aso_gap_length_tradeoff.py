# Screen discovery — by MEASURED oligo length, never by a filename convention
# ─────────────────────────────────────────────────────────────────────────────────────────────
#: ⭐ THIS IS THE ONE CONSUMER THAT LEGITIMATELY NEEDS MORE THAN ONE GEOMETRY, and it is served
#: `aso_screen_sets.iter_geometries` — one geometry at a time, as a mapping — rather than a pooled
#: list. The distinction is the whole point: this module compares geometries and must never average
#: across them, so it holds one set per geometry and combines them only where it says it is doing
#: so, per readout, in the open. There is no call in `aso_screen_sets` that would have handed it one
#: mixed bag, so "compares geometries" and "pools geometries" are different code rather than one
#: keystroke apart.
def _screen_geometry(screen):
    """The oligo length a committed screen ACTUALLY ran at, measured from its own designs.

    ⛔ MEASURED, BECAUSE THE PROVENANCE FIELD DOES NOT EXIST ON MOST OF THEM. `method.parameters`
    was added to this lane on 2026-08-13 and cannot be backfilled, so every screen committed before
    that date states its database, its program and its threshold and NOT its geometry. The length of
    the oligonucleotide the screen searched is in the file regardless — it is the thing that ran —
    and reading it is the difference between knowing and assuming which panel a count belongs to.

    ⭐ THE MEASUREMENT MOVED TO `aso_screen_sets` (2026-08-14) and this is a thin adapter. It was
    one of five hand-written copies of the same rule; four of them checked only the LENGTH, and a
    screen also states where its gap is. The loader checks both, which matters most in THIS module,
    since a gap window is the quantity it compares.
    """
    try:
        return ass.measure_oligo_len(ass.BLAST_SCREEN, screen)
    except ass.GeometryError:
        return None


def _screen_depth(screen):
    """(recorded ceiling or None, max hits stored on any design) — how deep this screen searched.

    The second is EVIDENCE rather than a parameter: retention was 15 by default, so a screen storing
    more than 15 hits on some design cannot have run at the default. It is the only depth signal the
    pre-2026-08-13 screens carry, and it is what makes a deep re-screen distinguishable from the
    shallow one beside it without trusting a filename.
    """
    params = (screen.get("method") or {}).get("parameters") or {}
    stored = max((len(o.get("offtargets") or []) for o in (screen.get("oligos") or [])), default=0)
    return params.get("blast_hitlist_size"), stored


def _discover(family):
    """{(oligo_len, junction_label): [(filename, artifact)]} over one artifact family.

    ⛔ THE PARTITION IS THE LOADER'S, NOT THIS MODULE'S (2026-08-14). This walked the directory
    itself and measured the length inline — correct, and a second implementation of a rule five
    other modules also needed, which is how one of them ends up with a different one. It now
    iterates `aso_screen_sets.iter_geometries`, which measures the same way AND additionally refuses
    any screen whose stated `gap_region_1based` disagrees with what it holds. A screen graded
    against one window and counted against another is the silent form of the geometry bug, and this
    module — which compares gap windows for a living — is the last place that should be reading one.
    """
    found = {}
    for geom, screens in ass.iter_geometries(family, root=HERE):
        for s in screens:
            label = s.junction_label
            if not label:
                continue
            found.setdefault((geom.oligo_len, label), []).append((s.name, s.artifact))
    return found


def _same_depth_siblings(cands, chosen_art):
    """Screens of the same junction run at a PROVABLY identical depth to the chosen one.

    ⛔ THE TEST IS THE RECORDED PAIR, AND ONLY THE RECORDED PAIR. Pooling a default-ceiling screen
    with a deep one produces a number that describes neither population — the defect 5233cf867
    corrected in the collapse artifact, where a widening glob moved a manuscript-quoted median from
    2.14 to 4.55 with no science behind it. A screen carrying no `parameters` block cannot prove its
    depth, so it never joins a union; for such junctions the union is the single chosen screen and
    nothing changes.
    """
    want = _screen_depth(chosen_art)[0], (chosen_art.get("method") or {}).get(
        "parameters", {}).get("saved_hits_per_design")
    if want[0] is None or want[1] is None:
        return []
    out = []
    for fn, art in cands:
        got = _screen_depth(art)[0], (art.get("method") or {}).get(
            "parameters", {}).get("saved_hits_per_design")
        if got == want:
            out.append((fn, art))
    return out


def _pick_deepest(cands):
    """The deepest screen for one (geometry, junction), with the evidence that says it is deepest.

    ⭐ AND THE SAME-DEPTH SIBLINGS TRAVEL WITH IT, BECAUSE A TRANSPORT FAILURE IS PER DESIGN AND PER
    RUN (2026-08-13). NCBI dropped three of this lane's 96 design queries with "Remote end closed
    connection without response". Re-dispatching did not simply fill them: at TAF15 e11 the re-run
    returned the design that had failed and FAILED a different one that had succeeded, and at FUS e8
    it did the same. Every design the two runs both screened returned identical counts, so the two
    partial results are consistent and each holds what the other lost.
    ⛔ THE FIX IS A UNION AT READ TIME, NOT A MERGED FILE. Editing one screen to carry another's
    record would be a hand-built artifact that no single run produced — the exact thing
    `test_every_committed_screen_predates_the_block_and_none_was_hand_backfilled` exists to catch.
    Both runs stay on disk exactly as CI wrote them, the union is computed here, and every design
    records which file supplied its record.
    ⚠ THE FAILURES LANDING ON DIFFERENT DESIGNS IN DIFFERENT RUNS IS ITSELF THE EVIDENCE that they
    are transport-random rather than a property of a sequence — which is what makes unioning them
    legitimate rather than cherry-picking the friendlier answer.
    """
    def rank(item):
        _, art = item
        ceiling, stored = _screen_depth(art)
        return (ceiling or 0, stored)
    fn, art = max(cands, key=rank)
    ceiling, stored = _screen_depth(art)
    return {
        "screen": fn,
        "blast_hitlist_size_recorded": ceiling,
        "max_hits_stored_on_a_design": stored,
        # ⚠ The two are different kinds of statement and must not render alike. A recorded ceiling is
        # a parameter the run wrote down; a stored-hit count is an inference from the output, and it
        # can only ever prove that retention EXCEEDED a value, never that the search ceiling did.
        "depth_evidence": ("recorded in the artifact's parameters block"
                           if ceiling else
                           f"no parameters block — retention exceeded the default 15 on some design "
                           f"({stored} stored), which a default run cannot produce"
                           if stored > 15 else
                           "no parameters block and no design stores more than the default retention "
                           "of 15, so the depth of this screen is UNKNOWN from the artifact alone"),
        "_n_candidates_seen": len(cands),
        "union_of_same_depth_screens": sorted(f for f, _ in _same_depth_siblings(cands, art)),
    }


def _union_rows(cands, chosen):
    """Per-design records unioned across same-depth screens of one junction, screened records winning.

    A design is taken from the chosen screen where that screen has it; where the chosen screen
    records a transport failure and a same-depth sibling screened it, the sibling's record is used
    and NAMED. A design no run screened stays a failure — the union recovers records, it never
    invents one.
    """
    by_file = dict(cands)
    order = [chosen["screen"]] + [f for f in chosen["union_of_same_depth_screens"]
                                  if f != chosen["screen"]]
    merged = {}
    for fn in order:
        art = by_file.get(fn)
        if art is None:
            continue
        for seq, row in _blast_rows(art).items():
            have = merged.get(seq)
            if have is None or (have.get("status") != "screened" and row.get("status") == "screened"):
                merged[seq] = {**row, "_from_screen": fn}
    return merged


def recount_loci(oligo):
    """Distinct loci and gap-spanning-risk loci, RECOUNTED from the stored hits with today's parser.

    ⭐ PUBLIC, AND IT BECAME PUBLIC BECAUSE A SECOND CONSUMER NEEDED IT AND DID NOT HAVE IT
    (2026-08-16). `research/manuscripts/submission_tables.py` was reading the screens'
    `n_loci_with_a_gap_spanning_hit` straight into Tables 2 and 3's deep columns — the very field
    the block below says must not be read — so Table 2 printed 17 gap-spanning loci for TCF12 e5
    where Table 4 and §3.3 printed 1, for the same molecule at the same depth. The remedy is this
    function, imported; a second implementation of the recount is how the two tables come to
    disagree again with nobody able to say which is right.

    ⛔⛔ THE STORED `n_distinct_loci` AND `n_loci_with_a_gap_spanning_hit` ARE NOT USED, BECAUSE THEY
    WERE COMPUTED AT SCREEN TIME BY A PARSER THAT WAS WRONG (2026-08-13, fixed in 5233cf867).
    `locus_of` took the gene symbol as the last parenthesised token BEFORE THE FIRST COMMA, so every
    gene whose own description contains a comma lost its symbol and fell back to its accession —
    `Homo sapiens germ cell-less 1, spermatogenesis associated (GMCL1), mRNA` split to a head with no
    parenthesis at all, and nine GMCL1 transcript variants were counted as NINE separate loci.
    Measured on this lane's own lead reagent: the 5-6-5 `GGGCATATCATCAAAC` carried
    `n_loci_with_a_gap_spanning_hit: 14`, of which five were real symbols and NINE were GMCL1
    accession fallbacks. Recounted with the fixed parser it is SIX.

    ⚠ THE ERROR IS ONE-DIRECTIONAL: a failed parse can only SPLIT a locus, never merge two, so every
    stored count is an over-count and every correction moves down. That makes the stale field unsafe
    in exactly the way that matters here — an inflated locus count reads as a dirtier reagent than
    the evidence supports, and this artifact compares reagents.

    ⛔ AND IT IS ONLY EXACT WHERE THE HIT LIST IS COMPLETE. The screen computed its counts over ALL
    ranked hits; this recount sees only the stored ones. Where the two agree the recount is exact;
    where the list is truncated it is a LOWER bound over a sample, and the pair is returned with
    `exact: False` rather than quoted as a measurement. Nothing here silently mixes the two.
    """
    from junction_aso_locus_collapse import locus_of  # noqa: PLC0415
    hits = oligo.get("offtargets") or []
    near = oligo.get("n_offtarget_near_matches")
    exact = near is not None and len(hits) == near
    risk = [h for h in hits if str(h.get("risk") or "").startswith("true_cleavage")]
    return {
        "n_distinct_loci": len({locus_of(h) for h in hits}),
        "n_loci_with_a_gap_spanning_hit": len({locus_of(h) for h in risk}),
        "loci_with_a_gap_spanning_hit": sorted({locus_of(h) for h in risk}),
        "exact": exact,
        "_basis": ("recounted from the complete stored hit list with the corrected locus parser"
                   if exact else
                   "LOWER BOUND — recounted over a truncated stored list, so loci beyond it are "
                   "unseen; the screen's own field is not substituted because it was produced by "
                   "the superseded parser and over-counts"),
    }


def _blast_rows(screen):
    """{antisense: per-design counts} from one gap-resolved screen, orientation status carried."""
    sys.path.insert(0, HERE)
    from junction_aso_offtarget import screen_orientation_status  # noqa: PLC0415
    status = screen_orientation_status(screen)
    rows = {}
    for o in screen.get("oligos") or []:
        if o.get("status") != "screened":
            rows[o.get("antisense_5to3")] = {"status": o.get("status"), "error": o.get("error")}
            continue
        near = o.get("n_offtarget_near_matches")
        saved = len(o.get("offtargets") or [])
        loci = recount_loci(o)
        rows[o["antisense_5to3"]] = {
            "status": "screened",
            "n_offtarget_near_matches": near,
            "n_true_cleavage_risk": o.get("n_true_cleavage_risk"),
            "n_minus_strand_not_hybridisable": o.get("n_minus_strand_not_hybridisable"),
            "n_gap_disrupted_no_cleavage": o.get("n_gap_disrupted_no_cleavage"),
            "loci": loci,
            # ⚠ WHAT THE SCREEN ITSELF RECORDED, KEPT BESIDE THE RECOUNT AND NEVER INSTEAD OF IT.
            # Retained so a reader can see the size and direction of the parser correction on this
            # exact design rather than having to take the recount on trust.
            # ⛔ THIS BLOCK ONCE ENDED "it is superseded, and nothing downstream reads it", AND THAT
            # SECOND CLAUSE WAS FALSE WHEN IT WAS WRITTEN (corrected 2026-08-16). The field was
            # superseded here and nowhere else: `research/manuscripts/submission_tables._deep_lookup`
            # read `n_loci_with_a_gap_spanning_hit` straight off the screens into the deep columns of
            # Tables 2 and 3, so 30 of the 187 deep 16-mer records printed the inflated figure —
            # TCF12 e5 / GGGCATATCCATCAGA at 17 where the recount is 1, TCF12 e3 / GGGCATATCTGATCCA
            # at 56 where it is 6, and the lead reagent GGGCATATCATCAAAC at 14 where it is 6, the
            # same three numbers Table 4 and the Results already carried corrected. A note asserting
            # that a superseded field has no readers is a claim about every other module in the
            # repository, which a comment here cannot check and cannot keep true. What replaced it is
            # `research/manuscripts/tests/test_deep_locus_cells_are_the_recount.py`: it holds the two
            # tables' rendered cells against this recount and refuses the one reader that had gone
            # wrong. A new reader elsewhere would still be unguarded — so the honest statement is
            # that this field is superseded, not that nobody reads it.
            "_superseded_locus_counts_from_the_old_parser": {
                "n_distinct_loci": o.get("n_distinct_loci"),
                "n_loci_with_a_gap_spanning_hit": o.get("n_loci_with_a_gap_spanning_hit"),
            },
            # ⚠ RIGHT-CENSORED means the stored list is shorter than the count, so the strand of the
            # remainder is unrecoverable and no later pass can repair it. Named per design because
            # within one screen some designs are censored and some are not.
            "hit_list_complete": (near is not None and saved == near),
            "orientation": status,
        }
    return rows


