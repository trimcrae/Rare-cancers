# =================================================================================================
# Pointer resolution.
# =================================================================================================

#: A backticked artifact path: `analyses.B_outcome_by_partner.metastasis_reading`,
#: `cohorts[huang-2023-outcome].size_covariate`, `citations.huang2023.verification_note`.
_POINTER = re.compile(r"`([A-Za-z_][A-Za-z0-9_]*(?:\[[^\]`]+\]|\.[A-Za-z0-9_]+)+)`")

#: ⚠ A FILENAME IS NOT A POINTER. `emc_fusion_partner_pooling.py` has the shape of a dotted path and
#: is a path on disk; excluding it by EXTENSION rather than by name keeps a file added tomorrow out
#: of scope without anybody remembering to list it.
_FILE_SUFFIX = re.compile(r"\.(?:py|json|md|mjs|ya?ml|csv|sh|txt|pdf)$")

#: ⚠ POINTERS INTO A DIFFERENT FILE, DECLARED SO THAT AN UNRESOLVABLE ROOT IS A FAILURE RATHER THAN
#: A SHRUG. Each is named beside its own artifact's path in the sentence that uses it.
FOREIGN_POINTERS = {
    "per_gene.values": "research/modalities/gse28866-tumour-vs-normal.json (§3.6)",
    "registry.citations.masunaga2025": "research/data/emc-clinical-registry.json (Appendix A11)",
}


def _resolve(art, path):
    """Walk one `a.b[id].c` path through the artifact. Returns (ok, where_it_broke)."""
    node = art
    for tok in re.findall(r"\[[^\]]+\]|[A-Za-z0-9_]+", path):
        if tok.startswith("["):
            key = tok[1:-1]
            if not isinstance(node, list):
                return False, f"{tok} indexes something that is not a list of records"
            hit = [c for c in node if isinstance(c, dict) and c.get("id") == key]
            if not hit:
                return False, f"no record with id {key!r}"
            node = hit[0]
        else:
            if not isinstance(node, dict) or tok not in node:
                return False, f"{tok!r} is not a key here"
            node = node[tok]
    return True, None


def test_every_artifact_pointer_the_prose_names_resolves(prose, art):
    """⛔ A POINTER TO A KEY THAT DOES NOT EXIST IS A BROKEN CITATION OF THE EVIDENCE.

    Two appendix rows in this document pointed at
    `analyses.B_outcome_by_partner.counter_signal.metastasis_reading`; there is no `counter_signal`
    node, and the real path is `analyses.B_outcome_by_partner.metastasis_reading`. A reader
    following it finds nothing and cannot tell whether the claim or the path is wrong. A blind seat
    found it; the check costs nothing and finds the whole class.

    ⚠ THE FOREIGN ROOTS ARE DECLARED, NOT SKIPPED. A path whose first segment is not a top-level key
    of this artifact is either a pointer into a different file — which must be in
    `FOREIGN_POINTERS` — or a typo. Skipping unknown roots silently would let a mistyped root pass
    as "not ours".
    """
    seen, broken, undeclared = 0, [], []
    for m in _POINTER.finditer(prose):
        path = m.group(1)
        if _FILE_SUFFIX.search(path):
            continue
        root = re.match(r"[A-Za-z0-9_]+", path).group(0)
        if root not in art:
            if path not in FOREIGN_POINTERS:
                undeclared.append(path)
            continue
        seen += 1
        ok, why = _resolve(art, path)
        if not ok:
            broken.append(f"{path} — {why}")
    assert not undeclared, (
        f"the manuscript names path-shaped references {undeclared} whose root is not a top-level "
        "key of the pooling artifact and which are not declared in FOREIGN_POINTERS. Either fix the "
        "path or declare which artifact it points into.")
    assert not broken, (
        "the manuscript points at artifact keys that do not exist: " + "; ".join(broken))
    assert seen >= 8, (
        f"only {seen} artifact pointers were found in the manuscript; this document cites its "
        "artifact by path throughout, so a collapse in that count means the pointer pattern has "
        "stopped matching rather than that the prose stopped pointing")


# =================================================================================================
# The census — what is NOT bound.
# =================================================================================================

#: The two drift-prone printed forms: an explicit `events/denom` fraction, and any printed rate —
#: integer percentages included, because the size defeater reaches the page as "78 %" and a census
#: that only read decimals would have called the paper's most-repeated share unwatched.
_CENSUS = re.compile(r"\d+/\d+|\d+(?:\.\d+)? ?%")


def _spans_by_bucket(flat):
    """(spans covered by a BINDING, spans covered by a DECLARATION) — kept apart on purpose.

    A figure inside a binding is WATCHED; a figure inside a declaration is only ACCOUNTED FOR. The
    census accepts either, and the ratchet below counts them separately so that moving a figure from
    the first bucket to the second is visible rather than silent.
    """
    bound, declared = [], []
    for _what, pattern, _value, _fold in BINDINGS:
        bound += [(m.start(), m.end()) for m in re.finditer(pattern, flat)]
    for _cls, pattern, _why in DECLARED_NOT_ARTIFACT_OWNED:
        declared += [(m.start(), m.end()) for m in re.finditer(pattern, flat)]
    return bound, declared


def _covered_spans(flat, art):
    bound, declared = _spans_by_bucket(flat)
    return bound + declared


def test_every_fraction_and_percentage_is_bound_or_declared(flat, art):
    """★★ THE SURFACE ENUMERATED, NOT SAMPLED (paper-hardening §8a).

    A guard is only as good as the set of sentences it reaches, and "how many did it reach" is a
    question you answer by counting, not by reading. Every `events/denom` fraction and every
    one-decimal rate in the manuscript is required to fall inside the span of a BINDING or of a
    declared not-artifact-owned construction. A new figure added to the prose with no binding fails
    here rather than joining the document unwatched.

    ⚠ THIS IS COVERAGE, NOT CORRECTNESS. It says only that something would notice a change; the
    bindings are what say the value is right.
    """
    spans = _covered_spans(flat, art)
    uncovered = []
    for m in _CENSUS.finditer(flat):
        if not any(s <= m.start() and m.end() <= e for s, e in spans):
            uncovered.append((m.group(0), flat[max(0, m.start() - 90):m.end() + 60]))
    assert not uncovered, (
        f"{len(uncovered)} printed figure(s) in the manuscript are bound to nothing and declared "
        "nowhere. Add a binding if the artifact owns the number, or a "
        "DECLARED_NOT_ARTIFACT_OWNED row with its reason class if it does not:\n"
        + "\n".join(f"  {v!r}  …{ctx}…" for v, ctx in uncovered))


def test_the_declared_exclusions_still_describe_real_sentences(flat):
    """⛔ AN EXCLUSION THAT NO LONGER MATCHES ANYTHING IS AN EXCLUSION NOBODY WILL EVER REMOVE.

    The list is meant to be short and reviewable. A row whose construction has left the document is
    dead weight that makes the exclusion set look larger — and, worse, hides the fact that the
    number it covered is gone.
    """
    dead = [pattern for _cls, pattern, _why in DECLARED_NOT_ARTIFACT_OWNED
            if not re.search(pattern, flat)]
    assert not dead, (
        "these declared exclusions match nothing in the manuscript any more, so delete them: "
        f"{dead}")


def test_no_share_above_one_hundred_percent_reaches_the_page(flat):
    """⛔ THE WRONG-DENOMINATOR CLASS, CAUGHT WHERE A REVIEWER WOULD SEE IT.

    A Wilson bound taken over the wrong denominator ran to 112.8 % once in this repository and
    reached a manuscript. This reads the shipped sentences rather than the module.
    """
    bad = [m for m in re.findall(r"\d+(?:\.\d+)? ?%", flat) if float(m.rstrip(" %")) > 100.0]
    assert not bad, f"the manuscript prints share(s) above 100 %: {bad}"


def test_the_guard_binds_a_material_share_of_the_documents_figures(flat, art):
    """★ A FLOOR UNDER COVERAGE, so that deleting bindings cannot quietly become the way to green.

    Not a target to chase — the census above is the real instrument. This is the ratchet that stops
    the file from being emptied: if a binding is removed, either the sentence went with it (and the
    census stays green while this falls) or the coverage really dropped.
    """
    bound, declared = _spans_by_bucket(flat)
    total = len(_CENSUS.findall(flat))
    assert total >= 100, (
        f"only {total} printed figures found; the census pattern has stopped matching the document")

    # ⚠ COUNT THE FIGURES A DECLARATION IS THE *ONLY* THING COVERING. Several declared patterns —
    # "95 %" above all — also fall inside bound constructions, so counting every declaration match
    # would report a document far less guarded than it is.
    only_declared = [m.group(0) for m in _CENSUS.finditer(flat)
                     if not any(s <= m.start() and m.end() <= e for s, e in bound)
                     and any(s <= m.start() and m.end() <= e for s, e in declared)]
    assert len(only_declared) <= 20, (
        f"{len(only_declared)} figures rest on a declaration alone: {sorted(set(only_declared))}. "
        "That list is meant to stay short and reviewable; a growing exclusion set is how a guard "
        "stops measuring anything.")
    in_bindings = sum(1 for m in _CENSUS.finditer(flat)
                      if any(s <= m.start() and m.end() <= e for s, e in bound))
    assert in_bindings >= 90, (
        f"only {in_bindings} of {total} printed figures sit inside a binding; bindings have been "
        "removed without the sentences they read going with them")
