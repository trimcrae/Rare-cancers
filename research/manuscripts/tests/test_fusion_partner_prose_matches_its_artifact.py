def _required(path, what):
    """⛔ An artifact that is not there is a finding, never a silent pass.

    Both paths are `git ls-files`-tracked, so absence is a broken tree rather than a partial
    checkout, and a guard that disappears with its input is indistinguishable from one that never
    ran.
    """
    if not os.path.exists(path):
        pytest.fail(f"{what} is missing at {path}. It is committed, so restore or regenerate it "
                    "rather than passing over the assertions that depend on it.")
    return path


def _load_prose():
    return open(_required(PAPER, "the fusion-partner manuscript"), encoding="utf-8").read()


def _load_artifact():
    return json.load(open(_required(ARTIFACT, "the fusion-partner pooling artifact"),
                          encoding="utf-8"))


def _flat(text):
    """The prose with hard wrapping collapsed and markdown emphasis removed.

    Two normalisations, both for the same reason — a pattern must bind the SENTENCE, not the
    typography around it:

      * the manuscript wraps at ~110 columns, so nearly every construction worth binding straddles
        a line break ("mean size\\n(13.7 vs 7.3 cm, P = .024)");
      * the same quantity is bolded in one section and plain in another (the abstract's
        "**one enters the primary pool**" against §5's "**one** enters the primary pool"), so a
        pattern written against one placement of `**` silently stops matching at the other — and a
        pattern that has stopped matching is a guard that has silently stopped guarding.

    ⚠ Removing `*` is safe in THIS document and the census proves it rather than assuming it: the
    only asterisks it contains are emphasis and gene-name italics.
    """
    return re.sub(r"\s+", " ", text).replace("*", "")


def _pct(x):
    """A rate as the manuscript prints it. The artifact stores it already rounded to one decimal."""
    return f"{float(x):.1f}"


def _fisher(x):
    """A post-hoc Fisher p as both the artifact and the prose print it.

    ⚠ `%g` IS THE WRONG RENDER HERE and it was the first thing tried: it turns `1.0` into `1`, and
    the trial-alone contrast really does print "1.0" in the abstract and in §3.1's table. `repr` of
    the loaded float is the shortest round-trip form, which is exactly what the generator wrote.
    """
    return repr(float(x))


def _hr(x):
    """A hazard ratio as the prose prints it — two decimals ("HR 30.60") over a stored `30.6`."""
    return f"{float(x):.2f}"


def _pubp(x):
    """A SOURCE'S OWN p-value as the prose prints it: no leading zero ("P = .004" for `0.004`).

    ⚠ These are the published papers' tests quoted verbatim, not the post-hoc Fisher values this
    repository computes; the artifact keeps them apart (`published_p_values` versus
    `fisher_exact_two_sided_p`) and so does every binding below.
    """
    s = f"{float(x):g}"
    assert s.startswith("0."), f"a published p-value of {x} is not of the form 0.xxx"
    return s[1:]


_WORDS = {0: "zero", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
          8: "eight", 9: "nine", 10: "ten", 11: "eleven", 12: "twelve", 13: "thirteen",
          14: "fourteen", 58: "fifty-eight"}


def _word(n):
    """A count that reaches the page as a WORD is still a count, and binding it as one is the point.

    ⛔ RAISES ON AN UNMAPPED VALUE rather than falling back to digits: the failure this file exists
    for is a number changing, and a helper that quietly renders `four` as `4` when the artifact
    moves from three to four would make exactly that change invisible.
    """
    n = int(n)
    if n not in _WORDS:
        raise KeyError(f"{n} has no spelled-out form here; add it deliberately, do not guess")
    return _WORDS[n]


def _frac(stratum):
    """`events/denom` exactly as the prose prints a stratum."""
    return f"{int(stratum['events'])}/{int(stratum['denom'])}"


def _lr_pair(a):
    """Both cohorts' local-recurrence arms, in the order §3.3 states them.

    ⚠ ONE CONSTRUCTION, EIGHT GROUPS, ON PURPOSE. The sentence's whole point is that the two cohorts
    run in OPPOSITE directions; binding each rate separately would let a swap that keeps every digit
    correct pass, which is the arm-swap mutation class this file already carries two cases of.
    """
    pc = a["analyses"]["B_outcome_by_partner"]["local_recurrence"]["per_cohort"]
    out = []
    for cohort in ("agaram-2014-outcome", "huang-2023-outcome"):
        for arm in ("TAF15::NR4A3", "EWSR1::NR4A3"):
            out += [_frac(pc[cohort][arm]), _pct(pc[cohort][arm]["percent"])]
    return tuple(out)


def _prev_pooled(a):
    """The prevalence pool's TAF15 events and denominator, re-derived from the pooled records."""
    pooled = a["analyses"]["C_partner_prevalence"]["cohorts_pooled"]
    by_id = _by_id(a)
    ev = sum(by_id[c]["counts"]["TAF15::NR4A3"] for c in pooled)
    dn = sum(sum(by_id[c]["counts"].values()) for c in pooled)
    return ev, dn


def _prev_shares(a):
    """Per-cohort TAF15 share for every pooled prevalence series, as the prose rounds it."""
    by_id = _by_id(a)
    return {c: round(100.0 * by_id[c]["counts"]["TAF15::NR4A3"]
                     / sum(by_id[c]["counts"].values()), 1)
            for c in a["analyses"]["C_partner_prevalence"]["cohorts_pooled"]}


def _prev_pct(a, cohort_id):
    return _pct(_prev_shares(a)[cohort_id])


def _sjogren(a):
    c = _by_id(a)["sjogren-2003-prevalence"]["counts"]
    return c["TAF15::NR4A3"], sum(c.values())


def _sjogren_frac(a):
    ev, dn = _sjogren(a)
    return f"{ev}/{dn}"


def _sjogren_pct(a):
    ev, dn = _sjogren(a)
    return _pct(round(100.0 * ev / dn, 1))


def _prev_counterfactual_frac(a):
    ev, dn = _prev_pooled(a)
    sev, sdn = _sjogren(a)
    return f"{ev + sev}/{dn + sdn}"


def _prev_counterfactual_pct(a):
    ev, dn = _prev_pooled(a)
    sev, sdn = _sjogren(a)
    return _pct(round(100.0 * (ev + sev) / (dn + sdn), 1))


# =================================================================================================
# The bindings.
#
# Each is (what, pattern, value, fold) where `value` is computed FROM THE ARTIFACT and `pattern`
# captures the same quantity out of the construction that states it. A one-group pattern expects a
# string; a multi-group pattern expects a tuple, so a pair of numbers stated together cannot drift
# apart — which is why a table row is one binding rather than six.
# =================================================================================================

BINDINGS = []


def bind(what, pattern, value, fold=False):
    """Register one binding.

    `fold=True` compares case-insensitively and is used ONLY where the captured value is a count
    spelled as a WORD: the same count opens a sentence as "Three" in the abstract and sits
    mid-sentence as "three" in §2.5, and capitalisation is a typographic fact about position rather
    than a claim about the evidence. ⛔ It is never set on a binding that captures digits, where
    every character is part of the number.
    """
    BINDINGS.append((what, pattern, value, fold))
    return pattern


def _by_id(art):
    return {c["id"]: c for c in art["cohorts"]}


def _endpoint(art, endpoint):
    return [c for c in art["cohorts"] if c["endpoint"] == endpoint]


