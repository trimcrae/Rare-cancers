"""Every number the FUSION-PARTNER manuscript prints, tied to the artifact field that computes it.

⛔ WHY THIS EXISTS — THE SAME ONE-OF-A-PAIR SHAPE, ONE PAPER OVER.
`research/manuscripts/fusion-partner/emc-fusion-partner-stratification.md` states in its own opening
that **every number below has one home**: `emc-fusion-partner-pooling.json`, generated by
`emc_fusion_partner_pooling.py`. The artifact side of that promise is guarded —
`test_emc_fusion_partner_pooling_check.py` proves `--check` refuses a hand-edited artifact — but
**nothing read the prose against it**. Measured 2026-08-26: 94 test modules name the sibling
`fusion-junction-aso` submission and 2 name `fusion-partner`, neither a numbers guard. So a figure
could drift in the manuscript, disagree with the artifact that produces it, and every test in the
repository would still pass.

That is not hypothetical for this document. Four rounds of blind adversarial review took its blocker
count 3 -> 2 -> 9, and several of the nine were exactly this class, each found by a human-equivalent
reader one round after it was introduced:

  * "of its 16 citation records, 11 carry a `verification_note`" — the artifact's count was 12;
  * two appendix rows pointed at `analyses.B_outcome_by_partner.counter_signal.metastasis_reading`,
    a key that does not exist (the real one is `analyses.B_outcome_by_partner.metastasis_reading`);
  * `cohorts_identified` / `cohorts_pooled` were TYPED into the generator and undercounted the
    moment a cohort was added;
  * an analysis verdict stated a claim absolutely where the prose stated it bounded.

⛔⛔ EVERY SITE THAT STATES THE QUANTITY, NOT WHETHER IT APPEARS SOMEWHERE. The sibling guard
(`test_journal_article_numbers.py`) first asserted `value in prose` and a mutation test walked
through three of nine corruptions, because one figure stood at three sites and corrupting ONE left
the others standing. Every assertion here therefore captures the number out of the CONSTRUCTION that
states it and checks EVERY match, via `re.findall` in the parametrized test below. Counted in the
committed text: "46.7" appears 4 times, "10.3" 6, "78 %" 6, "18.2" 6, "0.0034" 6, "24.8–69.9" 4,
"30.60" 3 and "43.4" 3 — so the failure mode is not hypothetical for this document either.

⛔ THE ASSERTIONS ARE ON DERIVED VALUES, NEVER ON REMEMBERED ONES. Each binding computes what the
prose should say from the artifact and looks for that. A failure means the manuscript and its
evidence have diverged — fix whichever is wrong, but do not relax the binding, and never paste the
artifact's current value in as a literal to make it green.

⚠ ROUNDING AND FORMATTING, HANDLED EXPLICITLY RATHER THAN BY LOOSENING THE MATCH.
The generator already rounds every rate to ONE decimal before writing it (`percent`,
`ci95_lo_percent`, `ci95_hi_percent`, `comparator_minus_taf15_percentage_points`), so there is no
second rounding decision to make here and `_pct` is a pure `%.1f` render of the committed float.
Three formats differ from the artifact's own and each is converted, not tolerated:
  * hazard ratios print with two decimals in the prose ("HR 30.60") and are stored as `30.6` — `_hr`;
  * the sources' own p-values print without the leading zero ("P = .004") and are stored as `0.004`
    — `_pubp`;
  * a handful of counts reach the page as WORDS ("three", "fifty-eight") — `_word`, which raises on
    an unmapped value rather than guessing.

⭐ MEASURED, 2026-08-26 — 36 of 36 mutations caught, 22 of them SINGLE-SITE.
Each mutation was applied to a `cp -al` clone (never the working tree), written as a new file and
`os.replace`d so the shared inode could not carry it back, and asserted LANDED by digest and by
occurrence count BEFORE the gate's answer was read — a mutation that never applies reports exactly
what a guard that never fires reports. An unmutated clone was run first as the positive control.
The set: 22 single-site corruptions of figures stated at 2-5 sites each (46.7 % at all three of its
homes in turn, 18.2 % at two of its five, 0.0034, 78 %, HR 30.60, 23, 9.2, 43.4, and both appendix
restatements); 2 arm swaps that leave every digit correct; 8 corruptions of a figure with a single
home; a pointer typo; an unbound figure inserted into the prose; and 6 GENERATOR mutations
regenerated through `emc_fusion_partner_pooling.py`, which is the edit that would really happen.
⚠ ONE FINDING FROM THE HARNESS ITSELF, recorded because it cost a restore: the generator writes its
artifact IN PLACE, the clone shares the inode, and the first run regenerated a MUTATED artifact
straight into the working tree. Break the link before regenerating — `cp -al` is not isolation.

⚠ WHAT IS DELIBERATELY NOT BOUND, AND WHY IT IS ENUMERATED RATHER THAN LEFT OUT.
Some printed numbers are not the artifact's to own: the 95 % confidence LEVEL, which the evidence
contract fixes and the artifact only ever echoes; the "≈27 %" the field quotes, which this paper
exists partly to correct; a figure whose one home is a different artifact; a DOI that happens to
contain a slash between digits; and a retained SUPERSEDED quotation whose whole purpose is to
preserve a number this document no longer asserts.
Excluding those silently would make the guard's coverage a matter of whatever happened to pass, so
they are declared in `DECLARED_NOT_ARTIFACT_OWNED` with a reason class, and
`test_every_fraction_and_percentage_is_bound_or_declared` fails on any printed fraction or rate that
is in neither bucket. That census is what stops the exclusion list growing to make the guard green.
"""
