#!/usr/bin/env node
// method-watch-backfill — one-off sweep over a PAST window the live watch never covered.
//
// WHY. The clinical / treatment-news watch landed 2026-08-24. Before that the newsletter had no
// source that could carry a trial readout, an approval or a program halt (see the section comment
// in method-watch.mjs), and the weekly field-scan Routine that was supposed to cover the same
// ground by web search has delivered nothing since 2026-07-13 — it was agent-created, so it has no
// repo grant and dies at its own `git checkout`. So roughly two months of clinical news went
// unread by BOTH layers. This script reads that window.
//
// It cannot be done with the live watch: those feeds are windowed to the last N days, which is
// correct for a weekly digest and useless for a backfill. Google News caps a query's results, so a
// single 60-day query silently returns a recent slice and looks complete. This sweeps in SLICES
// (default 14 days) and reports each slice's own hits, so coverage is even across the window
// rather than bunched at the end.
//
// It imports NEWS_FEEDS / TRIALS from method-watch.mjs rather than restating them: a backfill that
// asked different questions than the live watch would not tell us what the live watch would have
// caught, which is the whole question.
//
// Usage:  node scripts/method-watch-backfill.mjs <from:YYYY-MM-DD> <to:YYYY-MM-DD> [out.md] [sliceDays]
// NETWORK: news.google.com, clinicaltrials.gov

import { writeFileSync } from "node:fs";
import { CTGOV, NEWS_FEEDS, TRIALS, decodeEntities, feedUrl, fetchText, parseFeed } from "./method-watch.mjs";

const [, , FROM, TO, OUT = "research/method-watch-backfill.md", SLICE = "14"] = process.argv;
if (!/^\d{4}-\d{2}-\d{2}$/.test(FROM || "") || !/^\d{4}-\d{2}-\d{2}$/.test(TO || "")) {
  console.error("usage: method-watch-backfill.mjs <from YYYY-MM-DD> <to YYYY-MM-DD> [out.md] [sliceDays]");
  process.exit(2);
}

function slices(from, to, days) {
  const out = [];
  let a = new Date(from + "T00:00:00Z");
  const end = new Date(to + "T00:00:00Z");
  while (a < end) {
    const b = new Date(Math.min(a.getTime() + days * 86400000, end.getTime()));
    out.push([a.toISOString().slice(0, 10), b.toISOString().slice(0, 10)]);
    a = b;
  }
  return out;
}

// Same dedupe key as the email headline block: the headline text before the outlet suffix. One
// story carried by nine outlets is one story, and across slices it can also repeat verbatim.
const key = (t) => t.split(" - ")[0].toLowerCase().replace(/[^a-z0-9]+/g, " ").trim().slice(0, 70);

async function main() {
  const win = slices(FROM, TO, Number(SLICE));
  const L = [];
  L.push(`# Method-watch BACKFILL — ${FROM} to ${TO}`);
  L.push("");
  L.push(`Generated by \`scripts/method-watch-backfill.mjs\` over **${win.length} slices of ${SLICE} days**,`);
  L.push(`reusing the live watch's own query set (\`NEWS_FEEDS\` / \`TRIALS\` in \`method-watch.mjs\`) so this`);
  L.push(`reports what the live watch WOULD have surfaced had it existed. ⚠ **Press sources are LEADS,**`);
  L.push(`**NOT EVIDENCE** — read the primary record before any claim leaves this file (CLAUDE.md §7).`);
  L.push("");
  L.push(`⚠ **This is a RECONSTRUCTION, not a recording.** Google News ranks and caps results per query,`);
  L.push(`and it indexes what is still reachable today — an item that appeared and was later delisted is`);
  L.push(`gone. Absence here is therefore NOT evidence that nothing happened in a slice.`);
  L.push("");

  const seen = new Map();
  for (const f of NEWS_FEEDS) {
    L.push("");
    L.push(`## ${f.key}`);
    L.push(`*Unlocks:* ${f.trigger}`);
    let n = 0;
    for (const [a, b] of win) {
      let items = [];
      try {
        items = parseFeed(await fetchText(feedUrl(f, `after:${a}+before:${b}`)), 40);
      } catch (e) {
        L.push(`- _${a}→${b}: feed failed: ${e.message}_`);
        continue;
      }
      const fresh = [];
      for (const it of items) {
        const k = key(it.title);
        if (!k || seen.has(k)) continue;
        seen.set(k, true);
        fresh.push(it);
      }
      if (!fresh.length) continue;
      L.push("");
      L.push(`**${a} → ${b}**`);
      for (const it of fresh.slice(0, 12)) {
        const d = Date.parse(it.date);
        const day = Number.isNaN(d) ? it.date : new Date(d).toISOString().slice(0, 10);
        L.push(`- **${day}** — ${it.title}${it.link ? ` — ${it.link}` : ""}`);
        n++;
      }
      if (fresh.length > 12) L.push(`- _…and ${fresh.length - 12} more in this slice (not listed)._`);
    }
    if (!n) L.push(`- _(nothing new across the whole window)_`);
  }

  // Registry side: one query per row over the window, by LAST UPDATE. Deeper page than the weekly
  // digest takes, because two months of movement is more rows than a weekly read needs.
  L.push("");
  L.push(`## Trial registry — records updated ${FROM} → ${TO}`);
  for (const t of TRIALS) {
    L.push("");
    L.push(`### ${t.key}`);
    const p = { format: "json", pageSize: "20", countTotal: "false",
      "filter.advanced": `AREA[LastUpdatePostDate]RANGE[${FROM},${TO}]`, sort: "LastUpdatePostDate:desc" };
    if (t.intr) p["query.intr"] = t.intr;
    if (t.term) p["query.term"] = t.term;
    if (t.cond) p["query.cond"] = t.cond;
    try {
      const j = JSON.parse(await fetchText(`${CTGOV}?${new URLSearchParams(p)}`));
      const st = j?.studies || [];
      if (!st.length) { L.push(`- _(no matching records)_`); continue; }
      for (const s of st) {
        const m = s.protocolSection || {};
        const phases = (m.designModule?.phases || []).join("/");
        const bits = [phases, m.statusModule?.overallStatus, m.sponsorCollaboratorsModule?.leadSponsor?.name]
          .filter(Boolean).join(" · ");
        const res = s.hasResults ? " · **results posted**" : "";
        L.push(`- **${m.statusModule?.lastUpdatePostDateStruct?.date || "?"}** — ` +
          `${(m.identificationModule?.briefTitle || "").replace(/\s+/g, " ").trim()} (${bits}${res}) — ` +
          `https://clinicaltrials.gov/study/${m.identificationModule?.nctId || ""}`);
      }
    } catch (e) {
      L.push(`- _query failed: ${e.message}_`);
    }
  }

  L.push("");
  L.push(`---`);
  L.push(`_${seen.size} distinct news headlines after dedupe. Triage, not decisions._`);
  writeFileSync(OUT, L.join("\n") + "\n");
  console.error(`wrote ${OUT} (${seen.size} distinct headlines)`);
}

main().catch((e) => { console.error("backfill failed:", e); process.exit(1); });
